// Bakes Natural Earth (world-atlas 50m) country outlines for the Middle East theater
// into src/data/map.js so the game ships with no runtime map dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoMercator, geoPath, geoBounds } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const countries = feature(topo, topo.objects.countries).features;

export const W = 1000, H = 760;
const BBOX = { west: 24, east: 64, south: 11, north: 42.5 };

const frame = {
  type: 'Feature',
  geometry: {
    type: 'Polygon',
    // Clockwise ring: d3-geo treats counter-clockwise rings as the complement (the rest of the globe).
    coordinates: [[[BBOX.west, BBOX.south], [BBOX.west, BBOX.north], [BBOX.east, BBOX.north], [BBOX.east, BBOX.south], [BBOX.west, BBOX.south]]],
  },
};
const projection = geoMercator().fitExtent([[0, 0], [W, H]], frame);
projection.clipExtent([[-20, -20], [W + 20, H + 20]]);
const path = geoPath(projection).digits(1);

const out = [];
for (const f of countries) {
  const [[w, s], [e, n]] = geoBounds(f);
  if (e < BBOX.west - 2 || w > BBOX.east + 2 || n < BBOX.south - 2 || s > BBOX.north + 2) continue;
  const d = path(f);
  if (!d) continue;
  const [cx, cy] = path.centroid(f);
  out.push({ id: f.id ?? f.properties.name, name: f.properties.name, d, cx: +cx.toFixed(1), cy: +cy.toFixed(1) });
}

const src = `// GENERATED by tools/build-map.mjs from world-atlas countries-50m (Natural Earth). Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const PROJ = { scale: ${projection.scale()}, tx: ${projection.translate()[0]}, ty: ${projection.translate()[1]} };
export function project(lon, lat) {
  const l = (lon * Math.PI) / 180, p = (lat * Math.PI) / 180;
  return [PROJ.scale * l + PROJ.tx, -PROJ.scale * Math.log(Math.tan(Math.PI / 4 + p / 2)) + PROJ.ty];
}
export const COUNTRIES = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/data/map.js', import.meta.url), src);
console.log(`wrote ${out.length} countries, ${(src.length / 1024).toFixed(0)} KB`);
